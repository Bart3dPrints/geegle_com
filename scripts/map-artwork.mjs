#!/usr/bin/env node
// Build-time artwork mapper.
//
// Maps catalog game ids to the UGS-Assets folders that contain each game's
// own images (the same publicly-served assets the game loads at runtime).
// The mapping is generated from an explicit id→folder list in
// scripts/artwork-map.json so the association is exact and auditable — no
// fuzzy guessing that could attach the wrong game's art.
//
// Output: src/data/artwork.ts (generated; do not hand-edit).

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const mapPath = path.join(root, 'scripts', 'artwork-map.json');
const outPath = path.join(root, 'src', 'data', 'artwork.ts');

const map = JSON.parse(await readFile(mapPath, 'utf8'));
const entries = Object.entries(map).sort(([a], [b]) => a.localeCompare(b));

const header = `// AUTO-GENERATED by scripts/map-artwork.mjs — do not edit by hand.
// Explicit, audited mapping of game id → UGS-Assets folder that contains
// that game's own images (same public origin the game itself loads from).
// GameArt picks a representative image at runtime with a graceful fallback.

export const ARTWORK_FOLDERS: Record<string, string> = `;

await writeFile(
  outPath,
  header + JSON.stringify(Object.fromEntries(entries), null, 2) + ';\n',
  'utf8'
);

console.log(`[artwork] mapped ${entries.length} games to asset folders.`);
