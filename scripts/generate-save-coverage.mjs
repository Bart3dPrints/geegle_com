#!/usr/bin/env node
// Generate the cloud-save coverage table.
//
// A local game gets automatic cloud saves when the service worker can inject
// the storage shim into its wrapper (see public/geegle-sw.js) and the wrapper
// actually hosts the game. Wrappers that only frame another origin store their
// progress on that origin, and single-file builds above the injector's size
// limit are passed through untouched: both are reported honestly instead of
// promising a save that cannot be captured.
//
// Only the first 32 KB of each wrapper is read (enough to find <head> and a
// frame tag), so the scan stays fast despite the size of the game library.
//
// Usage: node scripts/generate-save-coverage.mjs [--check]
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { catalogRoot, localFilename, readCatalogRows } from './catalog-data.mjs';

const gamesDir = new URL('public/games/', catalogRoot);
const output = new URL('src/data/saveCoverage.ts', catalogRoot);
const MAX_INJECT_BYTES = 24 * 1024 * 1024;
const HEAD_BYTES = 32 * 1024;

const idsByFile = new Map();
for (const row of readCatalogRows()) {
  const file = localFilename(row.path);
  if (file && !idsByFile.has(file)) idsByFile.set(file, row.id);
}

const injectable = [];
const crossOrigin = [];
const oversize = [];
const engines = { unity: 0, ruffle: 0, emscripten: 0, indexeddb: 0, localstorage: 0 };

for (const dirent of readdirSync(gamesDir, { withFileTypes: true })) {
  if (!dirent.isFile() || !dirent.name.toLowerCase().endsWith('.html')) continue;
  const file = new URL(dirent.name, gamesDir);
  const id = idsByFile.get(dirent.name) ?? dirent.name.replace(/\.html$/i, '');
  if (statSync(file).size > MAX_INJECT_BYTES) { oversize.push(id); continue; }
  const handle = readFileSync(file);
  const head = handle.subarray(0, HEAD_BYTES).toString('utf8');
  injectable.push(id);
  if (/Unity|unity/.test(head) || /\.unityweb|\.data\b/.test(head)) engines.unity += 1;
  if (/Ruffle|ruffle/.test(head)) engines.ruffle += 1;
  if (/emscripten|Module\.FS/.test(head)) engines.emscripten += 1;
  if (/indexedDB/.test(head)) engines.indexeddb += 1;
  if (/localStorage/.test(head)) engines.localstorage += 1;
  // A wrapper whose only content is a cross-origin frame runs the game on
  // another origin, so local storage here is not the game's storage.
  if (/<(?:iframe|frame)[^>]+src=["']https?:\/\//i.test(head) && !/<script\s+src=["'](?!https?:\/\/)/i.test(head)) {
    crossOrigin.push(id);
  }
}

const sort = (list) => list.sort();
const generated = `// Generated by scripts/generate-save-coverage.mjs from the shipped wrappers.\n`
  + `// Regenerate with: node scripts/generate-save-coverage.mjs\n`
  + `// Do not edit by hand.\n\n`
  + `/** Catalog ids the service worker can inject the storage shim into. */\n`
  + `export const INJECTABLE_GAMES = new Set<string>(${JSON.stringify(sort(injectable), null, 2)});\n\n`
  + `/** Wrappers that only embed another origin; local storage is not theirs. */\n`
  + `export const CROSS_ORIGIN_GAMES = new Set<string>(${JSON.stringify(sort(crossOrigin), null, 2)});\n\n`
  + `/** Single-file builds above the injector's size limit. */\n`
  + `export const OVERSIZE_GAMES = new Set<string>(${JSON.stringify(sort(oversize), null, 2)});\n\n`
  + `export const SAVE_ENGINE_COVERAGE = ${JSON.stringify(engines, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) {
    throw new Error('Save coverage table is stale; run node scripts/generate-save-coverage.mjs');
  }
} else {
  writeFileSync(output, generated);
}
console.log(`[saves] injectable=${injectable.length} crossOrigin=${crossOrigin.length} oversize=${oversize.length}`, engines);
