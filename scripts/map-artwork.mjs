#!/usr/bin/env node
// Generate the runtime index from reviewed, reuse-cleared records only.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const source = new URL('./artwork-map.json', import.meta.url);
const output = new URL('../src/data/artwork.ts', import.meta.url);
const { cleared } = JSON.parse(await readFile(source, 'utf8'));
const entries = Object.entries(cleared).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const fields = ['title', 'url', 'source', 'type', 'identityEvidence', 'reuseEvidence'];
const types = new Set(['official-og', 'official-icon', 'game-asset', 'gameplay-screenshot']);
for (const [id, record] of entries) {
  if (!id || !fields.every((field) => typeof record[field] === 'string' && record[field].trim()) ||
    !types.has(record.type) || !record.source.startsWith('https:')) {
    throw new Error(`Invalid reuse-cleared artwork record: ${id}`);
  }
  if (/^\/artwork\/[a-z0-9-]+\.webp$/.test(record.url)) {
    const image = await readFile(new URL(`../public${record.url}`, import.meta.url));
    const hash = createHash('sha256').update(image).digest('hex');
    if (image.toString('ascii', 0, 4) !== 'RIFF' || image.toString('ascii', 8, 12) !== 'WEBP' ||
      hash !== record.assetSha256) throw new Error(`Local artwork integrity mismatch: ${id}`);
  } else if (new URL(record.url).protocol !== 'https:') {
    throw new Error(`Invalid artwork image URL: ${id}`);
  }
}
const runtimeEntries = entries.map(([id, record]) => [id, Object.fromEntries(fields.map(field => [field, record[field]]))]);
const generated = '// Generated by scripts/map-artwork.mjs; edit scripts/artwork-map.json instead.\n' +
  'export const CLEARED_ARTWORK: Partial<Record<string, {\n' +
  fields.map((field) => `  ${field}: string;\n`).join('') +
  `}>> = ${JSON.stringify(Object.fromEntries(runtimeEntries), null, 2)};\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== generated) {
    throw new Error('Artwork index is stale; run node scripts/map-artwork.mjs');
  }
} else {
  await writeFile(output, generated, 'utf8');
}
console.log(`[artwork] ${entries.length} reuse-cleared catalog records.`);
