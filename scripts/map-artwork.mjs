#!/usr/bin/env node
// Generate the runtime artwork index.
//
// Two honest tiers:
//  - CLEARED_ARTWORK: licensed or explicitly reuse-cleared records from
//    scripts/artwork-map.json (the only tier with a documented license).
//  - CAPTURED_ARTWORK: artwork a game wrapper declares for itself, and title
//    screens captured from the copy of the game this repository distributes.
//    These identify the game on the same platform and claim no license.
//
// Every local image is verified: it must decode as WebP and match its recorded
// SHA-256, so a broken or swapped file can never reach the UI.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const fields = ['title', 'url', 'source', 'type', 'identityEvidence', 'reuseEvidence'];
const types = new Set(['official-og', 'official-icon', 'game-asset', 'gameplay-screenshot', 'owner-supplied']);

async function verify(entries, tier) {
  for (const [id, record] of Object.entries(entries)) {
    if (!id) throw new Error(`Missing id in ${tier}`);
    if (!fields.every((field) => typeof record[field] === 'string' && record[field].trim())) {
      throw new Error(`Invalid ${tier} artwork record: ${id}`);
    }
    if (!types.has(record.type)) throw new Error(`Invalid ${tier} artwork type: ${id}`);
    // Wrappers sometimes declare an http asset URL; it is upgraded when fetched.
    if (!/^https?:\/\//.test(record.source)) throw new Error(`Invalid ${tier} artwork source: ${id}`);
    if (!/^\/artwork\/[A-Za-z0-9_-]+\.webp$/.test(record.url)) throw new Error(`Invalid ${tier} artwork path: ${id}`);
    const image = await readFile(new URL(`public${record.url}`, root));
    if (image.toString('ascii', 0, 4) !== 'RIFF' || image.toString('ascii', 8, 12) !== 'WEBP') {
      throw new Error(`${tier} artwork is not a WebP image: ${id}`);
    }
    const hash = createHash('sha256').update(image).digest('hex');
    if (hash !== record.assetSha256) throw new Error(`${tier} artwork integrity mismatch: ${id}`);
  }
}

const { cleared } = JSON.parse(await readFile(new URL('./artwork-map.json', import.meta.url), 'utf8'));
const captured = JSON.parse(await readFile(new URL('./artwork/captured.json', import.meta.url), 'utf8'));
const capturedEntries = { ...(captured.assets ?? {}), ...(captured.screens ?? {}) };
// A licensed record always wins over a captured thumbnail for the same game.
for (const id of Object.keys(cleared)) delete capturedEntries[id];

await verify(cleared, 'cleared');
await verify(capturedEntries, 'captured');

function emit(name, records) {
  const entries = Object.entries(records).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `export const ${name}: Partial<Record<string, {\n${fields.map((field) => `  ${field}: string;\n`).join('')}}>> = ${JSON.stringify(
    Object.fromEntries(entries.map(([id, record]) => [id, Object.fromEntries(fields.map((field) => [field, record[field]]))])),
    null, 2,
  )};\n`;
}

const generated = '// Generated by scripts/map-artwork.mjs; edit scripts/artwork-map.json and\n'
  + '// scripts/artwork/captured.json instead.\n\n'
  + emit('CLEARED_ARTWORK', cleared) + '\n' + emit('CAPTURED_ARTWORK', capturedEntries);
const output = new URL('src/data/artwork.ts', root);

if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== generated) {
    throw new Error('Artwork index is stale; run node scripts/map-artwork.mjs');
  }
} else {
  await writeFile(output, generated, 'utf8');
}
console.log(`[artwork] ${Object.keys(cleared).length} licensed and ${Object.keys(capturedEntries).length} captured records.`);
