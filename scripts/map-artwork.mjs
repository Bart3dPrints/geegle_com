#!/usr/bin/env node
// Generate the runtime index from reviewed records, never from research leads.
import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('./artwork-map.json', import.meta.url);
const output = new URL('../src/data/artwork.ts', import.meta.url);
const { verified } = JSON.parse(await readFile(source, 'utf8'));
const entries = Object.entries(verified).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const fields = ['title', 'url', 'source', 'type', 'identityEvidence'];
const types = new Set(['official-og', 'official-icon', 'game-asset', 'gameplay-screenshot']);
for (const [id, record] of entries) {
  if (!id || !fields.every((field) => typeof record[field] === 'string' && record[field].trim()) ||
    !types.has(record.type) || new URL(record.url).protocol !== 'https:' ||
    new URL(record.source).protocol !== 'https:') {
    throw new Error(`Invalid verified artwork record: ${id}`);
  }
}
const generated = '// Generated by scripts/map-artwork.mjs; edit scripts/artwork-map.json instead.\n' +
  `export const VERIFIED_ARTWORK = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== generated) {
    throw new Error('Artwork index is stale; run node scripts/map-artwork.mjs');
  }
} else {
  await writeFile(output, generated, 'utf8');
}
console.log(`[artwork] ${entries.length} reviewed catalog records.`);
