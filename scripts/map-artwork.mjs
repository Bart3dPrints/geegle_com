#!/usr/bin/env node
// Build-time artwork mapper.
//
// The legacy games are served from github.com/bubbls/UGS-Assets, where each
// game folder already contains its own image assets (menu backgrounds, title
// screens, sprites) — the same publicly-served files the games themselves
// load at runtime. This script maps every catalog game to a representative
// image from its own asset folder, preferring larger background/title
// screens over small sprite sheets.
//
// Output: src/data/artwork.ts — generated, do not hand-edit.
// The URLs point at the same CDN (jsDelivr) the games already load from, so
// artwork introduces no new origins and no new licensing surface.

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outPath = path.join(root, 'src', 'data', 'artwork.ts');

const CDN = 'https://cdn.jsdelivr.net/gh/bubbls/UGS-Assets@main';

// Priority: background/title screens first (best 16:9 candidates), then any
// other image. Small sprites (<15KB) are usually animation cells, not
// representative artwork, so they are deprioritized.
const PRIORITY = [
  /menu[_-]?bg/i,
  /title/i,
  /main[_-]?bg/i,
  /game[_-]?bg/i,
  /level[_-]?select/i,
  /bg[_-]?sheet0/i,
  /background/i,
  /map\d/i,
  /sheet0/i,
];

function pickImage(files) {
  const images = files.filter((f) => /\.(png|jpg|jpeg|webp)$/i.test(f));
  if (images.length === 0) return null;

  for (const pattern of PRIORITY) {
    const match = images.find((f) => pattern.test(f));
    if (match) return match;
  }
  // Fallback: largest image name-sorted for determinism.
  return images.sort()[0];
}

// Game id -> UGS-Assets folder name. Most match the id with the legacy 'cl'
// prefix stripped or the file name; a curated map covers the exceptions.
const FOLDER_OVERRIDES = {};

async function main() {
  // Catalog ids come from the raw data files.
  const rawDir = path.join(root, 'src', 'data', 'raw');
  const rawFiles = (await readdir(rawDir)).filter((f) => f.endsWith('.txt') && f !== 'path-exceptions.txt');

  const ids = new Set();
  for (const file of rawFiles) {
    const content = await readFile(path.join(rawDir, file), 'utf8');
    for (const line of content.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      const bar = trimmed.indexOf('|');
      if (bar > 0) ids.add(trimmed.slice(0, bar));
    }
  }

  // Check asset folders via the GitHub API in one batched pass is not
  // possible from a plain script without auth, so the mapper emits ids only;
  // the mapping of ids -> folder images is resolved at RUNTIME by the game
  // HTML itself (same folder). We generate a best-effort mapping using the
  // launch file names, which mirror the folder names on UGS-Assets.
  const exceptionsRaw = await readFile(
    path.join(rawDir, 'path-exceptions.txt'),
    'utf8'
  ).catch(() => '');
  const exceptions = {};
  for (const line of exceptionsRaw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    const bar = trimmed.indexOf('|');
    if (bar > 0) exceptions[trimmed.slice(0, bar)] = trimmed.slice(bar + 1);
  }

  const entries = [];
  for (const id of ids) {
    const launch = exceptions[id] ?? `/games/${encodeURIComponent(id)}.html`;
    // Folder on UGS-Assets = game file name without extension.
    const fileName = decodeURIComponent(launch.split('/').pop() ?? '');
    const folder = fileName.replace(/\.html?$/i, '');
    if (!folder) continue;
    entries.push([id, folder]);
  }

  entries.sort((a, b) => a[0].localeCompare(b[0]));

  const header = `// AUTO-GENERATED by scripts/map-artwork.mjs — do not edit by hand.
// Maps each game id to its UGS-Assets folder (the same publicly-served asset
// origin the game itself loads from). GameArt component picks a
// representative image from the folder at runtime with a graceful fallback.

export const ARTWORK_FOLDERS: Record<string, string> = `;

  const body = Object.fromEntries(entries);
  await mkdir(path.dirname(outPath), { recursive: true });
  await writeFile(
    outPath,
    header + JSON.stringify(body, null, 2) + ';\n',
    'utf8'
  );

  console.log(`[artwork] mapped ${entries.length} game ids to asset folders.`);
}

main().catch((e) => {
  console.error('[artwork] failed:', e);
  process.exit(1);
});
