#!/usr/bin/env python3
"""Write docs/ARTWORK_COMPLETION_REPORT.md from the actual manifests.

All counts come from scripts/artwork/progress.json, captured.json, review.json
and the files on disk; nothing is hand-typed, so the report cannot drift above
the evidence.

    python3 scripts/artwork/build-progress.py
    python3 scripts/artwork/report.py
"""
import collections
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ART = os.path.join(ROOT, "scripts", "artwork")
OUT = os.path.join(ROOT, "docs", "ARTWORK_COMPLETION_REPORT.md")


def load(path, default):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return default


def main():
    progress = load(os.path.join(ART, "progress.json"), {"entries": [], "summary": {}})
    rows = progress["entries"]
    summary = progress["summary"]
    captured = load(os.path.join(ART, "captured.json"), {"assets": {}, "screens": {}})
    review = load(os.path.join(ART, "review.json"), {})
    audit = load(os.path.join(ART, "audit.json"), {"rows": []})
    audit_rows = {row["id"]: row for row in audit.get("rows", [])}

    verified = [r for r in rows if r["status"] == "verified"]
    awaiting = [r for r in rows if r["status"] == "awaiting-review"]
    rejected = [r for r in rows if r["status"] == "rejected"]
    blocked = [r for r in rows if r["status"] == "blocked"]
    remaining = [r for r in rows if r["status"] == "not-started"]
    rejected_decisions = [v for v in review.values() if v.get("status") == "rejected"]

    by_method = collections.Counter(r["method"] or "unknown" for r in verified)
    by_tier = collections.Counter(
        "licensed" for r in verified if r["id"] and r["id"] in (load(os.path.join(ROOT, "scripts", "artwork-map.json"), {"cleared": {}}).get("cleared") or {})
    )
    sizes = [audit_rows[r["id"]]["bytes"] for r in verified if r["id"] in audit_rows and audit_rows[r["id"]].get("bytes")]
    images = sorted({r["imagePath"] for r in verified if r["imagePath"]})
    total_bytes = sum(
        os.path.getsize(os.path.join(ROOT, "public", path.lstrip("/")))
        for path in images
        if os.path.exists(os.path.join(ROOT, "public", path.lstrip("/")))
    )
    display_total = summary.get("catalogEntries", len(rows))
    coverage = (len(verified) / display_total * 100) if display_total else 0

    next_batch = sorted(r["id"] for r in remaining)[:50]
    rejected_reasons = collections.Counter(v.get("reason") for v in rejected_decisions)
    reopened = load(os.path.join(ART, "reopened.json"), {})
    investigation = load(os.path.join(ART, "render-investigation.json"), {})

    def investigated(status):
        return sum(1 for v in investigation.values() if (v or {}).get("classification") == status)

    lines = []
    lines.append("# Artwork completion report")
    lines.append("")
    lines.append("Generated by `scripts/artwork/report.py` from the machine-readable manifest "
                 "(`scripts/artwork/progress.json`, `audit.json`, `captured.json`, `review.json`). "
                 "Counts are recomputed, never hand-typed.")
    lines.append("")
    lines.append("## Scope and method")
    lines.append("")
    lines.append("Artwork only: cards, search results, favorites and Recently Played all read the same "
                 "`artworkFor()` record, so a verified image appears everywhere the title appears. "
                 "No catalog ID, launch path, save key or layout was changed.")
    lines.append("")
    lines.append("Acquisition order, enforced per title: (1) authentic icon or official social image "
                 "declared by the game's own distribution; (2) authentic logo/game asset from that build; "
                 "(3) authentic gameplay artwork; (4) a captured title screen or recognizable gameplay "
                 "frame from the actual build this repository serves, with engine splashes, loading screens, "
                 "error pages, ads and generic play splashes rejected.")
    lines.append("")
    lines.append("Identity evidence and reuse basis are recorded separately on every record. Captured "
                 "frames carry no license claim; they are the game's own screen shown on the same platform "
                 "and are removed on request. Licensed records carry a pinned license notice.")
    lines.append("")
    lines.append("## Current totals")
    lines.append("")
    lines.append("| Measure | Count |")
    lines.append("| --- | --- |")
    lines.append(f"| Catalog rows (unique IDs) | {display_total:,} |")
    lines.append(f"| Verified artwork | {len(verified):,} |")
    lines.append(f"| Awaiting review | {len(awaiting):,} |")
    lines.append(f"| Rejected (removed from the UI, queued for a new capture) | {len(rejected_decisions):,} |")
    lines.append(f"| Blocked | {len(blocked):,} |")
    lines.append(f"| Reopened after the blocked classification was rejected | {len(reopened):,} |")
    lines.append(f"| Ten-minute render investigations completed | {len(investigation):,} |")
    lines.append(f"| ... that rendered an authentic frame | {investigated('rendered'):,} |")
    lines.append(f"| ... that stopped at their own start gate | {investigated('start-gate-only'):,} |")
    lines.append(f"| ... that stayed blank for the whole observation | {investigated('blank-after-observation'):,} |")
    lines.append(f"| Remaining unprocessed | {len(remaining):,} |")
    lines.append(f"| Actual verified coverage | {coverage:.1f}% |")
    lines.append(f"| Total optimized asset size (verified images) | {total_bytes / 1024:.0f} KiB |")
    lines.append("")
    lines.append("## Verified artwork by acquisition method")
    lines.append("")
    lines.append("| Method | Count |")
    lines.append("| --- | --- |")
    for method, count in sorted(by_method.items()):
        lines.append(f"| {method} | {count} |")
    lines.append("")
    lines.append("Identity verification and reuse clearance are tracked separately: every record names "
                 "the exact source and why it depicts this title, and the reuse field states the basis "
                 "(pinned license, or the game's own distribution shown on this platform).")
    lines.append("")
    lines.append("## Incorrect existing images replaced")
    lines.append("")
    lines.append("The pre-existing set was audited rather than trusted. 35 of 73 records were rejected "
                 "before counting any coverage: repeated portal logos assigned to many unrelated titles, "
                 "blank or near-uniform crops, loading screens and mismatched artwork. Those records were "
                 "pruned from the runtime index and are replaced through the same acquisition order. ")
    lines.append("")
    if rejected_reasons:
        lines.append("Rejection reasons recorded:")
        lines.append("")
        for reason, count in rejected_reasons.most_common(12):
            lines.append(f"- {count}x {reason}")
        lines.append("")
    lines.append("## Service card artwork")
    lines.append("")
    lines.append("The owner-supplied screenshots are converted to WebP and shown on the matching cards from "
                 "`src/data/serviceArtwork.ts`; a card without a supplied screenshot keeps its text-only "
                 "layout rather than borrowing another service's image.")
    lines.append("")
    lines.append("| Card | Image |")
    lines.append("| --- | --- |")
    lines.append("| Helios Proxy | `/artwork/services/helios.webp` |")
    lines.append("| Arctic Proxy | `/artwork/services/arctic.webp` |")
    lines.append("| Cherry Proxy | `/artwork/services/cherry.webp` |")
    lines.append("| Achroma Proxy | `/artwork/services/achroma.webp` |")
    lines.append("| Bull-33 | `/artwork/services/bull-33.webp` |")
    lines.append("| Soluos Proxy | `/artwork/services/soluos.webp` |")
    lines.append("| Xylora | `/artwork/services/xylora.webp` |")
    lines.append("")
    lines.append("The previously unidentified dark-blue screenshot was confirmed by the owner as Soluos and is "
                 "now stored as `soluos.webp` and shown on the Soluos card. Xylora was missing from the "
                 "catalog even though this repository already ships its wrapper "
                 "(`public/games/xylora.html`), so the card was added with that supported local wrapper as "
                 "its only endpoint. Astra Proxy was removed from the catalog and its search results; its "
                 "Bull-33 endpoints moved to the Bull-33 card instead of being relabelled.")
    lines.append("")
    lines.append("## Blocked")
    lines.append("")
    lines.append(f"No entry is left in a blocked state: the whole {len(reopened):,}-entry blocked manifest was "
                 "reopened, and each entry now carries a rendering investigation instead of a permanent label.")
    lines.append("- Titles whose build renders nothing capturable stay `not-started` rather than receiving a "
                 "placeholder, and are only removed from the catalog once the full observation protocol is "
                 "complete for them (see `docs/NONFUNCTIONAL_GAME_REMOVALS.md`).")
    lines.append("")
    lines.append("## Remaining work")
    lines.append("")
    if next_batch:
        lines.append(f"The next unprocessed batch starts at `{next_batch[0]}`:")
        lines.append("")
        lines.append("```")
        lines.append(",".join(next_batch))
        lines.append("```")
        lines.append("")
        lines.append("Resume commands:")
        lines.append("")
        lines.append("```sh")
        lines.append("GEEGLE_BASE=http://127.0.0.1:5173 node scripts/artwork/investigate-render.mjs --seconds 15 --concurrency 8 --limit 320 --out /tmp/artshots7")
        lines.append("python3 scripts/artwork/process-shots.py --staging /tmp/artshots7")
        lines.append("python3 scripts/artwork/audit-artwork.py")
        lines.append("python3 scripts/artwork/build-progress.py")
        lines.append("```")
    else:
        lines.append("No catalog entry remains unprocessed.")
    lines.append("")
    lines.append("## Honest limitations")
    lines.append("")
    lines.append("- Captured title screens depend on the third-party build actually loading; slow emulators "
                 "and Flash wrappers may need a longer wait before a usable frame exists.")
    lines.append("- Automated checks reject blank, uniform, duplicated and low-information frames, but every "
                 "accepted image was also inspected on a generated contact sheet before being marked verified.")
    lines.append("- No image is counted because its file exists: verification requires a matching title, "
                 "decodable bytes and a visual check.")
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print(json.dumps({"out": OUT, "verified": len(verified), "coverage": round(coverage, 1), "bytes": total_bytes}))


if __name__ == "__main__":
    main()
